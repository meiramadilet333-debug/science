type TranslationKey = keyof typeof kk;
type LocaleContextValue = { locale: Locale; setLocale: (locale: Locale) => void };
const LocaleContext = createContext<LocaleContextValue | null>(null);

function getInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'ru';
  try {
    const selected = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (selected === 'ru' || selected === 'kk') return selected;
    const profile: unknown = JSON.parse(window.localStorage.getItem(PROFILE_STORAGE_KEY) || 'null');
    if (profile && typeof profile === 'object' && 'interfaceLanguage' in profile &&
      (profile.interfaceLanguage === 'ru' || profile.interfaceLanguage === 'kk')) {
      return profile.interfaceLanguage;
    }
  } catch {
    return 'ru';
  }
  return 'ru';
}

let activeLocale: Locale = getInitialLocale();

export function translate(key: TranslationKey | string): string {
  if (activeLocale !== 'kk') return key;
  const trimmed = key.trim();
  if (!trimmed || !(trimmed in kk)) return key;
  const start = key.indexOf(trimmed);
  return `${key.slice(0, start)}${kk[trimmed as TranslationKey]}${key.slice(start + trimmed.length)}`;
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error('useLocale must be used within LocaleProvider.');
  return value;
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
  const setLocale = (next: Locale) => {
    activeLocale = next;
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
      const stored = window.localStorage.getItem(PROFILE_STORAGE_KEY);
      if (stored) {
        const profile: unknown = JSON.parse(stored);
        if (profile && typeof profile === 'object' && !Array.isArray(profile)) {
          window.localStorage.setItem(PROFILE_STORAGE_KEY, JSON.stringify({
            ...profile,
            interfaceLanguage: next,
          }));
        }
      }
    } catch (error) {
      console.warn('Could not persist the language preference.', error);
    }
    setLocaleState(next);
  };
  const value = useMemo(() => ({ locale, setLocale }), [locale]);
  useEffect(() => {
    activeLocale = locale;
    document.documentElement.lang = locale === 'kk' ? 'kk' : 'ru';
    document.title = translate('Научный навигатор');
    const description = translate('Рабочее пространство исследователя: от научной идеи до готового результата.');
    document.querySelector('meta[name="description"]')?.setAttribute('content', description);
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', description);
    document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', description);
  }, [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export const t = (key: TranslationKey | string): string => translate(key);
